// CompilePrompt 编译为注入认知大脑的底层系统提示词
func (p *Persona) CompilePrompt() string {
	var sb strings.Builder
	fmt.Fprintf(&sb, "你是【%s】，%s。\n你的性格特质：%s。\n\n【对话与行为准则】：\n",
		p.Name, p.Identity, p.Temperament)
	for _, r := range p.Rules {
		sb.WriteString("• " + r + "\n")
	}
	return sb.String()
}
